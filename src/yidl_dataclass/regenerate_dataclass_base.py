"""Deterministically regenerate the consumer's source-based YIDL runtime."""

from __future__ import annotations
import argparse
import difflib
import hashlib
from importlib.resources import files
from pathlib import Path
from collections.abc import Sequence
from yidl.concept_parser import compile_yidl_files
from yidl.generation.data_def_sys import emit_concept_runtime_source


def render_dataclass_base_source() -> str:
    directory = files("yidl_dataclass").joinpath("yidl")
    sources = {
        f"dataclass/{item.name}": item.read_text()
        for item in sorted(directory.iterdir(), key=lambda item: item.name)
        if item.name.endswith(".yidl")
    }
    concept = compile_yidl_files(sources, "dataclass/dataclass_base.yidl").concepts[
        "DataclassBase"
    ]
    source = emit_concept_runtime_source(
        concept.plan.build_data_definition(),
        resources=concept.resources,
        assembly_plan=concept,
    )
    provenance = "".join(
        f"# {name} sha256={hashlib.sha256(text.encode()).hexdigest()}\n"
        for name, text in sorted(sources.items())
    )
    return (
        "# Generated by yidl-dataclass-regenerate-base; do not edit.\n"
        + provenance
        + source
    )


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    target = Path(__file__).with_name("_generated_dataclass_base.py")
    rendered = render_dataclass_base_source()
    if args.write:
        target.write_text(rendered)
        return 0
    expected = target.read_text() if target.exists() else ""
    if rendered == expected:
        return 0
    print(
        "".join(
            difflib.unified_diff(
                expected.splitlines(True),
                rendered.splitlines(True),
                fromfile="committed-base",
                tofile="regenerated-base",
            )
        )
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
